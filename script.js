// Configuración de desbloqueo (cada 3 días a partir del cap 5)
const startDate = new Date();
const DAYS_PER_CHAPTER = 3;

let isDevMode = false;
let audioContext = null;
let isMusicPlaying = false;
let intervals = [];

// Elementos del DOM
const chaptersGrid = document.getElementById('chaptersGrid');
const devToggle = document.getElementById('devToggle');
const unlockedCountEl = document.getElementById('unlockedCount');
const progressBarFill = document.getElementById('progressBarFill');
const progressPercentage = document.getElementById('progressPercentage');
const chapterModal = document.getElementById('chapterModal');
const closeModal = document.getElementById('closeModal');
const modalChapterNum = document.getElementById('modalChapterNum');
const modalTitle = document.getElementById('modalTitle');
const modalText = document.getElementById('modalText');
const modalCopyBtn = document.getElementById('modalCopyBtn');
const musicToggle = document.getElementById('musicToggle');
const musicIcon = document.getElementById('musicIcon');
const musicText = document.getElementById('musicText');

document.addEventListener('DOMContentLoaded', () => {
  createFloatingHearts();
  renderChapters();
  setupEventListeners();
});

// Corazones flotantes 🤍
function createFloatingHearts() {
  const container = document.getElementById('heartsContainer');
  const heartCount = 15;
  
  for (let i = 0; i < heartCount; i++) {
    const heart = document.createElement('div');
    heart.className = 'floating-heart';
    heart.textContent = '🤍';
    heart.style.left = `${Math.random() * 100}%`;
    heart.style.animationDelay = `${Math.random() * 10}s`;
    heart.style.animationDuration = `${8 + Math.random() * 8}s`;
    container.appendChild(heart);
  }
}

function getChapterUnlockDate(chapterNum) {
  if (chapterNum <= 5) {
    return new Date(startDate.getTime() - 1000);
  }
  const daysToAdd = (chapterNum - 5) * DAYS_PER_CHAPTER;
  const unlockDate = new Date(startDate.getTime());
  unlockDate.setDate(unlockDate.getDate() + daysToAdd);
  return unlockDate;
}

function renderChapters() {
  intervals.forEach(clearInterval);
  intervals = [];
  chaptersGrid.innerHTML = '';

  const now = new Date();
  let unlockedCount = 0;

  chaptersData.forEach((ch) => {
    const unlockDate = getChapterUnlockDate(ch.chapter);
    const isUnlocked = isDevMode || now >= unlockDate;

    if (isUnlocked) unlockedCount++;

    const card = document.createElement('div');
    card.className = `chapter-card ${isUnlocked ? 'unlocked' : 'locked'}`;

    if (isUnlocked) {
      card.innerHTML = `
        <div>
          <div class="card-top">
            <span class="chapter-number">Capítulo ${ch.chapter}</span>
            <span class="chapter-icon">🤍</span>
          </div>
          <h3 class="chapter-title">${ch.title}</h3>
          <p class="chapter-preview">${ch.text}</p>
        </div>
        <button class="btn-read" onclick="openChapterModal(${ch.chapter})">Leer capítulo 🤍</button>
      `;
    } else {
      const timerId = `timer-${ch.chapter}`;
      card.innerHTML = `
        <div>
          <div class="card-top">
            <span class="chapter-number">Capítulo ${ch.chapter}</span>
            <span class="chapter-icon">🔒</span>
          </div>
          <h3 class="chapter-title">${ch.title}</h3>
          <div class="countdown-box">
            <div class="countdown-title">Disponible en</div>
            <div class="timer" id="${timerId}">Cargando...</div>
          </div>
        </div>
        <button class="btn-read" disabled>Bloqueado 🤍</button>
      `;
      startCountdown(timerId, unlockDate);
    }

    chaptersGrid.appendChild(card);
  });

  unlockedCountEl.textContent = unlockedCount;
  const percent = Math.round((unlockedCount / chaptersData.length) * 100);
  progressBarFill.style.width = `${percent}%`;
  progressPercentage.textContent = `${percent}%`;
}

function startCountdown(elementId, unlockDate) {
  function updateTimer() {
    const now = new Date();
    const diff = unlockDate - now;
    const el = document.getElementById(elementId);
    if (!el) return;

    if (diff <= 0) {
      renderChapters();
      return;
    }

    const days = Math.floor(diff / (1000 * 60 * 60 * 24));
    const hours = Math.floor((diff / (1000 * 60 * 60)) % 24);
    const minutes = Math.floor((diff / (1000 * 60)) % 60);
    const seconds = Math.floor((diff / 1000) % 60);

    el.textContent = `${days}d ${hours}h ${minutes}m ${seconds}s`;
  }

  updateTimer();
  const interval = setInterval(updateTimer, 1000);
  intervals.push(interval);
}

function openChapterModal(chapterNum) {
  const ch = chaptersData.find(c => c.chapter === chapterNum);
  if (!ch) return;

  modalChapterNum.textContent = `Capítulo ${ch.chapter}`;
  modalTitle.textContent = ch.title;
  modalText.textContent = ch.text;

  modalCopyBtn.onclick = () => {
    navigator.clipboard.writeText(ch.text).then(() => {
      const originalText = modalCopyBtn.innerHTML;
      modalCopyBtn.innerHTML = '<span>✅ ¡Copiado con éxito!</span>';
      setTimeout(() => {
        modalCopyBtn.innerHTML = originalText;
      }, 2000);
    });
  };

  chapterModal.classList.add('active');
}

function closeChapterModal() {
  chapterModal.classList.remove('active');
}

/* ==========================================
   MÚSICA: Lucho RK - "Por qué será" (Instrumental Web Audio)
   ========================================== */
function toggleMusic() {
  if (isMusicPlaying) {
    if (audioContext) audioContext.suspend();
    isMusicPlaying = false;
    musicIcon.textContent = '🎵';
    musicText.textContent = '🎵 Por qué será (Lucho RK - Instrumental)';
  } else {
    if (!audioContext) {
      initLuchoRkTheme();
    } else {
      audioContext.resume();
    }
    isMusicPlaying = true;
    musicIcon.textContent = '🎶';
    musicText.textContent = '⏸️ Pausar música';
  }
}

function initLuchoRkTheme() {
  audioContext = new (window.AudioContext || window.webkitAudioContext)();
  
  // Notas acordes inspiradas en la atmósfera y progresión de "Por qué será"
  const chordProgression = [
    [220.00, 261.63, 329.63], // Am
    [174.61, 220.00, 261.63], // F
    [196.00, 246.94, 293.66], // G
    [164.81, 196.00, 246.94]  // Em
  ];
  let chordIndex = 0;

  function playChord() {
    if (!isMusicPlaying || !audioContext) return;

    const currentChord = chordProgression[chordIndex];
    currentChord.forEach((freq, i) => {
      const osc = audioContext.createOscillator();
      const gain = audioContext.createGain();

      osc.type = i === 0 ? 'triangle' : 'sine';
      osc.frequency.value = freq;

      gain.gain.setValueAtTime(0, audioContext.currentTime);
      gain.gain.linearRampToValueAtTime(0.045, audioContext.currentTime + 0.8);
      gain.gain.exponentialRampToValueAtTime(0.0001, audioContext.currentTime + 3.2);

      osc.connect(gain);
      gain.connect(audioContext.destination);

      osc.start();
      osc.stop(audioContext.currentTime + 3.5);
    });

    chordIndex = (chordIndex + 1) % chordProgression.length;
    setTimeout(playChord, 3000);
  }

  playChord();
}

function setupEventListeners() {
  devToggle.addEventListener('change', (e) => {
    isDevMode = e.target.checked;
    renderChapters();
  });

  closeModal.addEventListener('click', closeChapterModal);
  chapterModal.addEventListener('click', (e) => {
    if (e.target === chapterModal) closeChapterModal();
  });

  musicToggle.addEventListener('click', toggleMusic);
}
